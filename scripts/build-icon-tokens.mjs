// Generates css/icon-tokens.css with a --icon-<name> token for every optimized icons/*.svg
import { readdirSync, writeFileSync } from 'node:fs';

const iconsDir = new URL('../icons/', import.meta.url);
const tokensFile = new URL('../css/icon-tokens.css', import.meta.url);

const names = readdirSync(iconsDir)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort();

const tokens = names.map((name) => `  --icon-${name}: url("/icons/${name}.svg");`);

writeFileSync(
  tokensFile,
  `/* Generated by scripts/build-icon-tokens.mjs, do not edit */\n:root {\n${tokens.join('\n')}\n}\n`,
);

console.log(`Generated ${names.length} icon tokens`);
