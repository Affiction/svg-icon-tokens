// Generates an IconName union type from the optimized icons/*.svg
// Usage: node scripts/build-icon-types.mjs [output path, default types/icon-name.ts]
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const iconsDir = new URL('../icons/', import.meta.url);
const outFile = resolve(process.argv[2] ?? fileURLToPath(new URL('../types/icon-name.ts', import.meta.url)));

const names = readdirSync(iconsDir)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort();

const members = names.length ? names.map((name) => `  | '${name}'`).join('\n') : '  never';

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/build-icon-types.mjs, do not edit\nexport type IconName =\n${members};\n`,
);

console.log(`Generated IconName with ${names.length} icons -> ${outFile}`);
